def quote_ident(name: str) -> str:
    """PG identifier — lowercase, double-quote sadece reserved word'de."""
    return name.lower()


def gen_raw_staging(table: TableMeta) -> str:
    tname = quote_ident(table.name)
    return f"""-- raw staging: {table.name}
CREATE TABLE workcube_mssql_raw.{tname} (
    run_id UUID NOT NULL,
    source_schema VARCHAR(128) NOT NULL,
    source_year SMALLINT,
    source_pk TEXT,
    raw_payload JSONB NOT NULL,
    extracted_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_raw_{tname}_run ON workcube_mssql_raw.{tname} (run_id);
"""


def gen_canonical_table(table: TableMeta, blocked: list) -> str:
    """23 matched tablo için full DDL."""
    tname = quote_ident(table.name)
    lines = [f"-- {table.name} (canonical, used by: {', '.join(table.reports[:3])}, rowCount={table.row_count})"]
    lines.append(f"CREATE TABLE workcube_mikrolink.{tname} (")
    lines.append("    source_schema VARCHAR(128) NOT NULL DEFAULT 'workcube_mikrolink',")

    # Columns
    col_defs = []
    for col in sorted(table.snapshot_columns, key=lambda c: c.ordinal):
        pg_type, block_reason = col.map_to_pg()
        if block_reason:
            blocked.append({
                "table": table.name,
                "column": col.name,
                "mssql_type": col.data_type,
                "max_length": col.max_length,
                "reason": block_reason,
            })
            # BLOCKED kolonları comment olarak ekle
            col_defs.append(f"    -- BLOCKED({block_reason}): {col.name} {col.data_type}(maxLen={col.max_length})")
            continue

        nullable = "" if col.nullable else " NOT NULL"
        identity = " GENERATED BY DEFAULT AS IDENTITY" if col.identity else ""
        col_defs.append(f"    {quote_ident(col.name)} {pg_type}{nullable}{identity},")

    lines.extend(col_defs)
    lines.append("    content_hash VARCHAR(64) NOT NULL,")
    lines.append("    migration_row_id BIGSERIAL,  -- surrogate (PK metadata snapshot'ta yok, Codex iter-4)")
    lines.append("    migrated_at TIMESTAMPTZ NOT NULL DEFAULT now(),")
    lines.append("    PRIMARY KEY (migration_row_id)  -- TODO: business PK manual review")
    lines.append(");")
    lines.append("")
    lines.append(f"CREATE INDEX idx_{tname}_hash ON workcube_mikrolink.{tname} (content_hash);")

    return "\n".join(lines) + "\n"


