class TableColumn:
    """MSSQL column metadata."""

    def __init__(self, snap: dict):
        self.name = snap["name"]
        self.data_type = snap.get("dataType", "").lower()
        self.max_length = snap.get("maxLength")  # int (-1 for MAX)
        self.nullable = snap.get("nullable", True)
        self.identity = snap.get("identity", False)
        self.pk = snap.get("pk", False)
        self.ordinal = snap.get("ordinal", 0)

    def map_to_pg(self) -> tuple[str, str | None]:
        """Returns (pg_type, blocked_reason). blocked_reason None ise OK."""
        base = self.data_type

        # String types
        if base in {"varchar", "nvarchar", "char", "nchar"}:
            if self.max_length == -1 or self.max_length is None:
                return "TEXT", None
            if self.max_length and self.max_length > 0:
                # nvarchar metadata bazen byte length verir; karakter için /2 (Unicode)
                # Konservatif: olduğu gibi al
                if base.startswith("n") and self.max_length > 1:
                    chars = self.max_length // 2 if self.max_length % 2 == 0 else self.max_length
                else:
                    chars = self.max_length
                pg_base = "VARCHAR" if base in {"varchar", "nvarchar"} else "CHAR"
                return f"{pg_base}({chars})", None
            return "TEXT", None

        if base == "varbinary":
            if self.max_length == -1:
                return "BYTEA", None
            return "BYTEA", None

        # Numeric — decimal/numeric scale eksikliği BLOCKED (Codex iter-4)
        if base in {"decimal", "numeric"}:
            # Snapshot'ta scale yok — finans precision için BLOCKED
            return "NUMERIC", "DECIMAL_SCALE_MISSING"

        # Direct map
        if base in MSSQL_TO_PG_TYPE_BASE:
            return MSSQL_TO_PG_TYPE_BASE[base], None

        # Unknown
        return "TEXT", f"UNKNOWN_TYPE:{base}"


class TableMeta:
    """Per-table metadata (annex + snapshot)."""

    def __init__(self, name: str):
        self.name = name
        self.is_parametric = False
        self.reports: list[str] = []
        self.parametric_schemas: set[str] = set()
        self.category = "?"
        self.snapshot_columns: list[TableColumn] = []
        self.row_count = 0


