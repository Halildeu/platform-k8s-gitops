def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--snapshot", required=True, type=Path)
    parser.add_argument("--annex", required=True, type=Path)
    parser.add_argument("--out", required=True, type=Path)
    parser.add_argument("--review-out", required=True, type=Path)
    parser.add_argument("--fk-out", required=True, type=Path)
    parser.add_argument("--unsupported-out", required=True, type=Path)
    args = parser.parse_args()

    snapshot, annex = load_inputs(args.snapshot, args.annex)
    metas = build_table_metadata(snapshot, annex)
    etl_scope = set(metas.keys())

    matched = sum(1 for m in metas.values() if not m.is_parametric and m.snapshot_columns)
    parametric = sum(1 for m in metas.values() if m.is_parametric)
    print(f"ETL scope: {len(etl_scope)} table", file=sys.stderr)
    print(f"  Matched canonical: {matched}", file=sys.stderr)
    print(f"  Parametric placeholder: {parametric}", file=sys.stderr)

    blocked: list[dict] = []

    # ============= V16 SQL =============
    sections: list[str] = [
        "-- Faz 16.2 V16 — generated by scripts/migration/generate_v16_sql.py\n",
        "-- Codex iter-4 AGREE: 23 matched canonical + 17 parametric placeholder\n",
        f"-- Tables: {len(etl_scope)} (matched={matched}, parametric={parametric})\n",
        "\nBEGIN;\n\n",
        "-- 00 EXTENSIONS\nCREATE EXTENSION IF NOT EXISTS citext;\nCREATE EXTENSION IF NOT EXISTS pgcrypto;\n\n",
        "-- 01 SCHEMAS\nCREATE SCHEMA IF NOT EXISTS workcube_mikrolink;\nCREATE SCHEMA IF NOT EXISTS workcube_mssql_raw;\nCREATE SCHEMA IF NOT EXISTS migration_audit;\n\n",
        AUDIT_DDL,
        "\n-- ===== 03 RAW STAGING + 04+05 FINAL TABLES =====\n\n",
    ]

    # Per-table DDL
    for tname in sorted(etl_scope):
        meta = metas[tname]
        if meta.is_parametric:
            sections.append(gen_parametric_placeholder(meta))
        elif meta.snapshot_columns:
            sections.append(gen_raw_staging(meta))
            sections.append("\n")
            sections.append(gen_canonical_table(meta, blocked))
        else:
            sections.append(f"-- WARNING: {tname} no snapshot columns — skipped\n")
        sections.append("\n")

    sections.append("\nCOMMIT;\n")

    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text("".join(sections))
    print(f"Wrote: {args.out} ({len(open(args.out).read().splitlines())} lines)", file=sys.stderr)

    # ============= Review markdown =============
    args.review_out.parent.mkdir(parents=True, exist_ok=True)
    args.review_out.write_text(gen_review_md(metas, blocked))
    print(f"Wrote: {args.review_out}", file=sys.stderr)

    # ============= FK candidates =============
    args.fk_out.parent.mkdir(parents=True, exist_ok=True)
    args.fk_out.write_text(gen_fk_candidates_md(snapshot, etl_scope))
    print(f"Wrote: {args.fk_out}", file=sys.stderr)

    # ============= Unsupported columns =============
    args.unsupported_out.parent.mkdir(parents=True, exist_ok=True)
    args.unsupported_out.write_text(gen_unsupported_md(blocked))
    print(f"Wrote: {args.unsupported_out} ({len(blocked)} blocked)", file=sys.stderr)

    print("DONE", file=sys.stderr)


if __name__ == "__main__":
    main()
