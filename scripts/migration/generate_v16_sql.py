def load_inputs(snapshot_path: Path, annex_path: Path) -> tuple[dict, dict]:
    with open(snapshot_path) as f:
        snapshot = json.load(f)
    with open(annex_path) as f:
        annex = yaml.safe_load(f)
    return snapshot, annex


def build_table_metadata(snapshot: dict, annex: dict) -> dict[str, TableMeta]:
    """Annex 2A + snapshot crossreference."""
    metas: dict[str, TableMeta] = {}
    snapshot_tables = snapshot.get("tables", {})

    for r in annex["reports"]:
        rname = r["report"]
        for t in r.get("tables", []):
            tname = t["name"]
            if tname not in metas:
                metas[tname] = TableMeta(tname)
            meta = metas[tname]
            meta.reports.append(rname)
            meta.category = r.get("category", "?")
            if t.get("parametric_schema"):
                meta.is_parametric = True
                meta.parametric_schemas.update(r.get("parametric_schemas", []))

    # Snapshot match
    for tname, meta in metas.items():
        if tname in snapshot_tables:
            tdata = snapshot_tables[tname]
            meta.row_count = tdata.get("rowCount", 0)
            meta.snapshot_columns = [TableColumn(c) for c in tdata.get("columns", [])]
        # Parametric tablolar canonical schema'da yok; placeholder

    return metas


