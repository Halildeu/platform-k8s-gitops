def gen_fk_candidates_md(snapshot: dict, etl_scope: set[str]) -> str:
    relationships = snapshot.get("relationships", [])
    candidates = [r for r in relationships if r.get("fromTable") in etl_scope and r.get("toTable") in etl_scope]

    lines = [
        "# V16 FK Candidates (Faz 16.2 Gün 3)\n\n",
        f"> Codex iter-3+4 verdict: FK MINIMAL — sadece markdown rapor, SQL üretme.\n",
        f"> Reconciliation 16.3.5 authoritative gate.\n\n",
        f"## Summary\n\n",
        f"- Total relationships in snapshot: {len(relationships)}\n",
        f"- Candidates (both ends in ETL scope): **{len(candidates)}**\n\n",
        "## FK candidates within ETL scope (manual review)\n\n",
    ]

    if candidates:
        lines.append("| From | From column | To | To column | Confidence |\n")
        lines.append("|---|---|---|---|---|\n")
        for r in candidates[:50]:
            lines.append(f"| `{r.get('fromTable')}` | `{r.get('fromColumn', '?')}` | `{r.get('toTable')}` | `{r.get('toColumn', '?')}` | {r.get('confidence', 'unknown')} |\n")
        if len(candidates) > 50:
            lines.append(f"\n... + {len(candidates) - 50} more (full list: snapshot relationships scope filtered)\n")
    else:
        lines.append("(No relationships in scope — annex tablolar arasında FK yok)\n")

    lines.append("\n## Karar\n\n")
    lines.append("Codex iter-3 AGREE: FK MINIMAL + NOT VALID + reconciliation authoritative.\n")
    lines.append("Bu liste manuel review için. SQL FK clause **gerekirse** review sonrası V16'a eklenir.\n")
    return "".join(lines)


def gen_unsupported_md(blocked: list) -> str:
    if not blocked:
        return "# V16 Unsupported Columns (boş — tüm kolonlar map'lendi)\n"

    by_reason = defaultdict(list)
    for b in blocked:
        by_reason[b["reason"]].append(b)

    lines = [
        "# V16 Unsupported / Blocked Columns (Faz 16.2 Gün 3)\n\n",
        f"> Codex iter-4 verdict: snapshot eksik metadata → FAIL FAST, BLOCKED kolon DDL'e eklenmez.\n\n",
        f"## Summary\n\n",
        f"- Total blocked: **{len(blocked)}**\n",
    ]
    for reason, items in by_reason.items():
        lines.append(f"- {reason}: {len(items)}\n")
    lines.append("\n## Per-reason detail\n\n")
    for reason, items in sorted(by_reason.items()):
        lines.append(f"### {reason}\n\n")
        lines.append("| Table | Column | MSSQL Type | maxLength |\n|---|---|---|---|\n")
        for b in sorted(items, key=lambda x: (x["table"], x["column"])):
            lines.append(f"| `{b['table']}` | `{b['column']}` | `{b['mssql_type']}` | {b['max_length']} |\n")
        lines.append("\n")
    lines.append("## Resolution\n\n")
    lines.append("- `DECIMAL_SCALE_MISSING`: Workcube admin'den scale netleştirilir (finans precision için kritik)\n")
    lines.append("- `UNKNOWN_TYPE`: Type mapping rule eklenmeli (`MSSQL_TO_PG_TYPE_BASE`)\n")
    lines.append("\nBLOCKED kolonlar **DDL'e eklenmez**, generator output'unda comment olarak tutulur. Manuel resolve sonrası generator rerun.\n")
    return "".join(lines)


